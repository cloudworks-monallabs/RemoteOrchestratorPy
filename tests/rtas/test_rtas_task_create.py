from pathlib import Path
from rtas.rtas_common import (the_rtas,
                          local_workdir,
                          remote_workdir,
                          CLUSTER_RESOURCES_DATADIR,
                          adming_ssh_private_key_file,
                          FileConfig,
                          rtas_taskify,
                          deployment_remote_workdir,
                          )

@rtas_taskify([the_rtas])
def task_sequence_generator(rtas):
    # ========================= local step pre ========================
    def step_local_step_pre(rtas):
        pass
        

    rtas.set_task_local_step_pre(step_local_step_pre, rtas)

    # ============================== end =============================

    # =========================== ship file ==========================
    rtas.set_task_ship_files_iter([FileConfig(Path(f"{local_workdir}/ship_file_1"),
                                             False,
                                             False,
                                             Path(f"{deployment_remote_workdir}/ship_file_1")
                                              )],
                                  deployment_remote_workdir
                                  )

    # ============================== end =============================
     
    def step_local_step_post(rtas):
        pass

    rtas.set_task_local_step_post(step_local_step_post, rtas)
    
    yield from rtas
    
    


def test_RTAS_sequence_default_usage():
    # 1. Generate the tasks
    # The decorator handles the instantiation of tasks across the all_rtas list
    tasks = list(task_sequence_generator())
    
    # Extract names for assertion
    # Base pattern is usually task_func_name:ipv6:id_args
    task_names = [f"{t['basename']}:{t['name']}" for t in tasks]
    
    # Define our base for assertions
    # Since ipv6 and id_args are used in the real basename, we find the first task's basename
    base = tasks[0]['basename']
    ip = the_rtas.ipv6
    # 2. Assert Task Presence and Order
    # The expected order generated by 'yield from rtas' should be:
    # _root_enter_ -> local_step_pre -> ship_files:_root_enter_ -> ship_file:... -> ship_files:_leaf_final_ -> local_step_post -> _leaf_final_
    
    expected_segments = [
        f"{base}:_root_enter_",
        f"{base}:{ip}:local_step_pre",
        f"{base}:{ip}:ship_files:_root_enter_",
        f"{base}:{ip}:ship_file:{deployment_remote_workdir}/ship_file_1",
        f"{base}:{ip}:ship_files:_leaf_final_",
        f"{base}:{ip}:local_step_post",
        f"{base}:_leaf_final_"
    ]

    for segment in expected_segments:
        assert segment in task_names, f"Missing expected task: {segment}"

    # 3. Verify the Dependency Chain (The "Baton Pass")
    
    # Task: local_step_pre should depend on _root_enter_
    pre_task = next(t for t in tasks if t['name'] == "local_step_pre")
    assert f"{base}:_root_enter_" in pre_task['task_dep']

    # Task: ship_files:_root_enter_ should depend on local_step_pre
    # This proves rtas.final_task was updated correctly after local_step_pre
    ship_root = next(t for t in tasks if t['name'] == "ship_files:_root_enter_")
    assert f"{base}:{ip}:local_step_pre" in ship_root['task_dep']

    # Individual ship_file task should depend on ship_files:_root_enter_
    ship_item = next(t for t in tasks if "ship_file:" in t['name'])
    assert f"{base}:{ip}:ship_files:_root_enter_" in ship_item['task_dep']

    # The group aggregator (leaf_final for shipping) should depend on the specific file
    ship_leaf = next(t for t in tasks if t['name'] == "ship_files:_leaf_final_")
    assert f"{base}:{ip}:ship_file:{deployment_remote_workdir}/ship_file_1" in ship_leaf['task_dep']

    # local_step_post should depend on ship_files:_leaf_final_
    post_task = next(t for t in tasks if t['name'] == "local_step_post")
    assert f"{base}:{ip}:ship_files:_leaf_final_" in post_task['task_dep']

    # 4. Verify Actions and Metadata
    # Check that ship_file task has the correct file_dep
    assert Path(f"{local_workdir}/ship_file_1") in ship_item['file_dep']
    
    # Check that local_step_pre has the action_wrapper applied
    # The action should be a tuple (wrapper, (rtas_instance,))
    assert callable(pre_task['actions'][0][0]) 
    
    print("\nRTAS Sequence Verified: Local-Pre -> Ship-Iter -> Local-Post Chain is intact.")
    
